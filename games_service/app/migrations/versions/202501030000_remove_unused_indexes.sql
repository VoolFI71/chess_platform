-- Удаление неиспользуемых индексов для оптимизации базы данных

-- Индекс на player_id в moves не используется в WHERE запросах
-- player_id используется только для хранения информации, но не для фильтрации
-- Индекс создается автоматически SQLAlchemy через index=True в модели
-- После удаления index=True из модели, индекс больше не будет создаваться автоматически
-- Если индекс уже существует, его можно удалить вручную через:
-- DROP INDEX IF EXISTS ix_moves_player_id;
-- Но так как мы уже удалили index=True из модели, новый индекс создаваться не будет

-- Составной индекс ix_moves_game_created_at не используется
-- Запросы используют ORDER BY move_index, а не created_at
-- Индекс на game_id уже есть, поэтому составной индекс избыточен
DROP INDEX IF EXISTS ix_moves_game_created_at;

